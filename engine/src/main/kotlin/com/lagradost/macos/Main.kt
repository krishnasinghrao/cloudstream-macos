/**
 * CloudStream macOS — headless scraper daemon (Tier 2).
 *
 * SEC-01: binds strictly to 127.0.0.1, never 0.0.0.0.
 * SEC-02: every endpoint except /health and relayed media reads requires `Authorization: Bearer <token>`;
 *         the token is ephemeral, generated by the Swift client at launch and
 *         delivered via stdin (preferred) or argv/env — never written to disk
 *         or logged.
 *
 * Usage: `java -jar daemon.jar <port> [token]` (token via stdin when omitted)
 *        (env fallback: CS_DAEMON_PORT / CS_DAEMON_TOKEN)
 */
private const val TAG = "Daemon"

/** Bearer token; constant-time compared on every request. Never logged. */
@Volatile
private var bearerToken: String = ""

/** Lines written by the supervisor onto our stdin: token, then launch options JSON. */
private val tokenLatch = java.util.concurrent.CountDownLatch(1)
private val optionsLatch = java.util.concurrent.CountDownLatch(1)
@Volatile
private var stdinToken: String? = null
@Volatile
private var stdinOptions: String? = null

fun main(args: Array<String>) {
    if (args.firstOrNull() == "--worker") {
        // One extension's sandboxed worker process (ADR-0016); never the control plane.
        com.lagradost.macos.worker.WorkerMain.run()
        return
    }
    if (args.firstOrNull() == "--self-test") {
        // Packaging gate: exercises the extension translation path on this runtime.
        val result = runCatching { PluginBridge.selfTest() }
        println(result.getOrElse { "failed: ${it.javaClass.name}: ${it.message}" })
        kotlin.system.exitProcess(if (result.isSuccess) 0 else 1)
    }
    val port = resolvePort(args)
    val (token, fromStdin) = resolveToken(args)
    // Over stdin the options line is mandatory (it carries managed policy); the
    // environment variable is a development fallback for env/argv launches only.
    DaemonRuntime.configure(if (fromStdin) {
        optionsLatch.await(10, java.util.concurrent.TimeUnit.SECONDS)
        LaunchOptions.parse(stdinOptions, required = true)
    } else LaunchOptions.parse(System.getenv("CS_DAEMON_OPTIONS")))

    require(token.length >= 8) {
        "SEC-02: bearer token too short (got ${token.length} chars; production uses 64-char hex)"
    }
    bearerToken = token

    val dataRootLock = runCatching { DataRootLock.acquire(CloudDirs.home.toPath()) }.getOrElse { failure ->
        // Another engine (usually a second copy of the app) owns this data:
        // a distinct exit status lets the app say so instead of retrying.
        System.err.println("cloudstream: data root is in use: ${failure.message}")
        kotlin.system.exitProcess(DataRootLock.IN_USE_EXIT_STATUS)
    }
    Runtime.getRuntime().addShutdownHook(Thread { dataRootLock.close() })
    // A shutdown hook that never returns must not leave an orphaned engine.
    ShutdownWatchdog.install()


    // Local structured logging (SEC-03) — first, so everything after is recorded.
    DaemonLog.init()
    DaemonLog.info("daemon.starting", mapOf("ipcVersion" to HealthDto.IPC_VERSION))
    Metrics.startedAtMs // initialize the uptime clock at launch, not at the first /health request

    // Persisted state: repositories, disabled providers, overrides, network.
    DaemonState.load()

    // Extension hosting: one sandboxed worker per extension (ADR-0016), or in-process for development.
    if (DaemonRuntime.options.isolation == LaunchOptions.ISOLATION_WORKER) {
        val runtime = com.lagradost.macos.worker.WorkerExtensionRuntime()
        RepositoryService.installations = InstallationManager(runtime, RepositoryService.transport)
        com.lagradost.macos.worker.WorkerPool.onQuarantine = { id, reason -> RepositoryService.installations.quarantine(id, reason) }
        Runtime.getRuntime().addShutdownHook(Thread({ com.lagradost.macos.worker.WorkerPool.beginShutdown() }, "worker-pool-shutdown"))
        com.lagradost.macos.worker.WorkerPool.onTranslation = { id, generation, hashes -> RepositoryService.installations.recordTranslation(id, generation, hashes) }
        com.lagradost.macos.worker.WorkerPool.onAssessment = { id, generation, report -> RepositoryService.installations.recordAssessment(id, generation, report) }
        // Extractors of one extension serve every extension's providers (RT-12).
        ExtractorRouter.install()
        MediaResolveBridge.install()
        DaemonLog.info("extensions.isolation", mapOf("mode" to "worker", "sandboxed" to runtime.sandboxed))
    }

    // HTTP stack: DoH resolver, response cache, anti-bot circuit, retries —
    // after state load so the persisted network settings apply at boot.
    NetworkSetup.install()
    ProviderRuntimeBootstrap.initialize()

    // Serve /health immediately; committed extensions restore in the background
    // with per-extension deadlines, crash quarantine and safe-mode support.
    val server = embeddedServer(Netty, host = "127.0.0.1", port = port) { module() }
    server.start(wait = false)
    val boundPort = kotlinx.coroutines.runBlocking { server.engine.resolvedConnectors().single().port }
    DaemonLog.info("daemon.listening", mapOf("port" to boundPort))
    // The app starts the engine on port 0 and learns the port from this line
    // on the engine's own stdout pipe (audit M1): nothing else can announce it.
    EngineHandshake.announce(boundPort)
    Thread({
        kotlinx.coroutines.runBlocking {
            try {
                RepositoryService.installations.migrateLegacyArtifacts()
                val result = RepositoryService.installations.restoreAll()
                DaemonLog.info("extensions.restored", mapOf("phase" to result.phase, "restored" to result.restored,
                    "failed" to result.failed, "quarantined" to result.quarantined))
                RepositoryService.installations.collectGarbage()
            } catch (failure: Throwable) {
                if (failure is VirtualMachineError && failure !is StackOverflowError) throw failure
                DaemonLog.error("extensions.restore_failed", mapOf("error" to failure.javaClass.simpleName))
            }
            // Periodic catalog refresh: revocations and automatic updates (plan T3.9).
            BackgroundRefresh.loop()
        }
    }, "extension-restore").apply { isDaemon = true }.start()
    Thread.currentThread().join()
}

fun Application.module() {
    install(ContentNegotiation) {
        json(Json {
            prettyPrint = false
            ignoreUnknownKeys = true
            encodeDefaults = true
        })
    }

    // SEC-02: bearer authentication on every endpoint except /health.
    intercept(ApplicationCallPipeline.Plugins) {
        // Nothing the engine answers may be kept in an HTTP cache: responses
        // carry links, per-link headers, keys and viewing history (audit M3).
        call.response.headers.append(io.ktor.http.HttpHeaders.CacheControl, "no-store")
        val path = call.request.path()
        if (path == "/health") return@intercept
        // A relayed media resource is read by the native player, which sends
        // one header set to every origin and so must not hold the token. Its
        // 256-bit id, issued to the authenticated client, is the credential.
        if (path.startsWith(MediaRelay.PATH_PREFIX) &&
            (call.request.httpMethod == HttpMethod.Get || call.request.httpMethod == HttpMethod.Head)) return@intercept

        val provided = call.request.headers["Authorization"].orEmpty()
        val expected = "Bearer $bearerToken"
        val ok = provided.length == expected.length &&
            MessageDigest.isEqual(provided.toByteArray(), expected.toByteArray())
        if (!ok) {
            call.respond(
                HttpStatusCode.Unauthorized,
                ErrorResponseDto(error = "unauthorized", detail = "missing or invalid bearer token"),
            )
            finish()
            return@intercept
        }

        // SEC-08: reject data and execution requests while application is locked.
        // /lock remains accessible so the authorized client can query or update lock state.
        // Downloads keep running behind the lock, so the routes they use stay open.
        if (DaemonLock.isLocked && path != "/lock" && path !in DaemonLock.downloadPaths) {
            call.respond(
                HttpStatusCode.Locked,
                ErrorResponseDto(error = "locked", detail = "Application is locked"),
            )
            finish()
            return@intercept
        }

        // The recovery gate protects persistent state. /lock and the download
        // routes (links, verifier jobs, relay registration) change only memory,
        // mirroring the lock gate above, so they stay usable during recovery.
        if (call.request.httpMethod != HttpMethod.Get && DaemonState.recoveryError != null &&
            path != "/lock" && path !in DaemonLock.downloadPaths) {
            call.respond(HttpStatusCode.ServiceUnavailable,
                ErrorResponseDto(error = "state recovery required", detail = DaemonState.recoveryError))
            finish()
        }
    }

    routing {
        get("/health") {
            Metrics.recordRequest("health")
            call.respond(
                HealthDto(
                    uptimeMs = System.currentTimeMillis() - Metrics.startedAtMs,
                    providersLoaded = PluginBridge.allProviders().size,
                    recoveryError = DaemonState.recoveryError,
                    extensions = RepositoryService.installations.restoreState.let {
                        com.lagradost.macos.models.ExtensionHealthDto(it.phase, it.restored, it.failed, it.quarantined)
                    },
                    safeMode = DaemonRuntime.safeMode,
                    policyManaged = DaemonRuntime.policy.managed,
                    isolation = isolationHealth(),
                    proof = call.request.headers[EngineHandshake.NONCE_HEADER]?.let { EngineHandshake.proof(bearerToken, it) },
                ),
            )
        }

        get("/lock") {
            call.respond(AppLockResponseDto(locked = DaemonLock.isLocked))
        }

        post("/lock") {
            val request = call.receive<AppLockRequestDto>()
            DaemonLock.setLocked(request.locked)
            call.respond(AppLockResponseDto(locked = DaemonLock.isLocked))
        }

        extensionRoutes()
        mediaRoutes()
    }

    DaemonLog.info("daemon.ready", mapOf("loopbackOnly" to true))
}

private fun resolvePort(args: Array<String>): Int {
    val fromArg = args.firstOrNull()?.toIntOrNull()
    val fromEnv = System.getenv("CS_DAEMON_PORT")?.toIntOrNull()
    val port = fromArg ?: fromEnv ?: error("usage: daemon <port> [token]")
    // Zero lets isolated build/test launches ask the OS for a free port without
    // racing another process. Production callers can keep their explicit port.
    require(port == 0 || port in 1024..65535) { "port out of range: $port" }
    return port
}

/**
 * Token resolution (SEC-02): stdin (preferred — invisible to `ps`) →
 * env → argv. stdin reads happen on a short-deadline thread so a missing
 * token never wedges startup when argv is used for development.
 */
private fun resolveToken(args: Array<String>): Pair<String, Boolean> {
    System.getenv("CS_DAEMON_TOKEN")?.let { return Pair(it, false) }

    if (args.size >= 2) {
        DaemonLog.warn("token.argv_used", mapOf("warning" to "token visible in process list; prefer stdin"))
        return Pair(args[1], false)
    }

    // One thread owns stdin: token line, launch-options line, then it becomes
    // the parent watchdog (EOF means the app is gone).
    val reader = Thread {
        try {
            val input = System.`in`.bufferedReader()
            val line = input.readLine()
            if (!line.isNullOrBlank()) stdinToken = line.trim()
            tokenLatch.countDown()
            val options = input.readLine()
            if (!options.isNullOrBlank()) stdinOptions = options.trim()
            optionsLatch.countDown()
            while (input.read() != -1) { /* wait for EOF */ }
        } catch (_: Exception) { /* stdin closed */ }
        tokenLatch.countDown()
        optionsLatch.countDown()
        if (stdinToken != null) {
            DaemonLog.info("daemon.parent_died", mapOf("reason" to "stdin EOF"))
            kotlin.system.exitProcess(0)
        }
    }
    reader.isDaemon = true
    reader.name = "StdinReaderWatchdog"
    reader.start()
    tokenLatch.await(3, java.util.concurrent.TimeUnit.SECONDS)

    val token = stdinToken ?: error("SEC-02: no bearer token provided (stdin, CS_DAEMON_TOKEN, or argv)")
    return Pair(token, true)
}

internal fun isolationHealth(): com.lagradost.macos.models.IsolationHealthDto {
    val runtime = RepositoryService.installations.runtimeForExtract as? com.lagradost.macos.worker.WorkerExtensionRuntime
        ?: return com.lagradost.macos.models.IsolationHealthDto(mode = LaunchOptions.ISOLATION_IN_PROCESS, sandboxed = false)
    return com.lagradost.macos.models.IsolationHealthDto(
        mode = LaunchOptions.ISOLATION_WORKER,
        sandboxed = runtime.sandboxed,
        runningWorkers = com.lagradost.macos.worker.WorkerPool.runningCount(),
    )
}

/**
 * How the app authenticates its engine (audit M1). The engine binds port 0 and
 * prints [announcement] on its stdout pipe, which only the app reads; the app
 * then sends a fresh nonce to /health and accepts the listener only when it
 * answers with [proof], computed from the launch token. The token never goes
 * to /health, so a process squatting on a port learns nothing.
 */
internal object EngineHandshake {
    const val NONCE_HEADER = "X-CloudStream-Nonce"
    const val PREFIX = "CLOUDSTREAM-ENGINE-LISTENING "
    private val nonceShape = Regex("^[0-9a-f]{32,128}$")

    fun announcement(port: Int): String = PREFIX + "{\"port\":$port,\"pid\":${ProcessHandle.current().pid()}}"

    fun announce(port: Int) {
        System.out.println(announcement(port))
        System.out.flush()
    }

    /** Null for a malformed nonce: nothing is computed over attacker-chosen bytes of arbitrary length. */
    fun proof(token: String, nonce: String): String? {
        if (token.isEmpty() || !nonceShape.matches(nonce)) return null
        val mac = javax.crypto.Mac.getInstance("HmacSHA256")
        mac.init(javax.crypto.spec.SecretKeySpec(token.toByteArray(Charsets.UTF_8), "HmacSHA256"))
        return java.util.HexFormat.of().formatHex(mac.doFinal("cloudstream-health-v1:$nonce".toByteArray(Charsets.UTF_8)))
    }
}
